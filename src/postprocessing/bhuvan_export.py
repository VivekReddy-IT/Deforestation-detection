"""
ISRO Bhuvan & Field GIS Export Module
Exports detected deforestation alerts into:
1. ISRO Bhuvan Geoportal KML format (compliant with NRSC standards)
2. Standalone GeoJSON RFC 7946 (WGS84)
3. Ranger Field Incident Action Sheets
"""

from typing import Dict, Any, List, Optional
import os
import json
import xml.etree.ElementTree as ET


def export_isro_bhuvan_kml(
    geojson_path: str,
    output_kml_path: str = "results/isro_bhuvan_deforestation_alerts.kml",
    project_title: str = "ISRO NRSC | Hasdeo Arand Deforestation Early Warning Alert",
) -> str:
    """Converts WGS84 GeoJSON deforestation polygons into an ISRO Bhuvan-compliant KML file

    with full telemetry (Alert ID, Area in Ha, Severity, Carbon Loss, UTM coordinates).
    """
    os.makedirs(os.path.dirname(os.path.abspath(output_kml_path)), exist_ok=True)

    if not os.path.exists(geojson_path):
        raise FileNotFoundError(f"GeoJSON file not found: {geojson_path}")

    with open(geojson_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    features = data.get("features", [])

    kml = ET.Element("kml", xmlns="http://www.opengis.net/kml/2.2")
    doc = ET.SubElement(kml, "Document")
    name_el = ET.SubElement(doc, "name")
    name_el.text = project_title
    desc_el = ET.SubElement(doc, "description")
    desc_el.text = "Generated by DeepForest-AI Dual-Stage Spatio-Temporal Sentinel-2 Pipeline for Forest Survey of India & ISRO NRSC Bhuvan."

    # Style: Critical Alert (>5 ha) - Bold Red
    style_crit = ET.SubElement(doc, "Style", id="critical_alert")
    line_crit = ET.SubElement(style_crit, "LineStyle")
    ET.SubElement(line_crit, "color").text = "ff0000ff"
    ET.SubElement(line_crit, "width").text = "3"
    poly_crit = ET.SubElement(style_crit, "PolyStyle")
    ET.SubElement(poly_crit, "color").text = "aa0000ff"  # Red with alpha

    # Style: High Alert (1-5 ha) - Orange
    style_high = ET.SubElement(doc, "Style", id="high_alert")
    line_high = ET.SubElement(style_high, "LineStyle")
    ET.SubElement(line_high, "color").text = "ff0080ff"
    ET.SubElement(line_high, "width").text = "2.5"
    poly_high = ET.SubElement(style_high, "PolyStyle")
    ET.SubElement(poly_high, "color").text = "aa0080ff"

    # Style: Moderate Alert (<1 ha) - Yellow
    style_mod = ET.SubElement(doc, "Style", id="moderate_alert")
    line_mod = ET.SubElement(style_mod, "LineStyle")
    ET.SubElement(line_mod, "color").text = "ff00ffff"
    ET.SubElement(line_mod, "width").text = "2"
    poly_mod = ET.SubElement(style_mod, "PolyStyle")
    ET.SubElement(poly_mod, "color").text = "aa00ffff"

    folder = ET.SubElement(doc, "Folder")
    ET.SubElement(folder, "name").text = "Active Deforestation Incidents"

    for feat in features:
        props = feat.get("properties", {})
        geom = feat.get("geometry", {})
        if geom.get("type") != "Polygon":
            continue

        alert_id = props.get("alert_id", "DEF-ALERT")
        area_ha = props.get("area_ha", 0.0)
        severity = props.get("severity", "Deforestation")
        urgency = props.get("urgency", "MONITORING")
        carbon = props.get("carbon_tco2", round(area_ha * 310.0, 1))
        utm = props.get("utm_coords", "N/A")
        center_lat = props.get("center_lat", 0.0)
        center_lon = props.get("center_lon", 0.0)

        placemark = ET.SubElement(folder, "Placemark")
        ET.SubElement(placemark, "name").text = f"{alert_id} ({area_ha} ha)"

        if area_ha >= 5.0:
            ET.SubElement(placemark, "styleUrl").text = "#critical_alert"
        elif area_ha >= 1.0:
            ET.SubElement(placemark, "styleUrl").text = "#high_alert"
        else:
            ET.SubElement(placemark, "styleUrl").text = "#moderate_alert"

        # Extended data table for Bhuvan
        ext_data = ET.SubElement(placemark, "ExtendedData")
        for k, v in [
            ("Incident_ID", alert_id),
            ("Cleared_Area_Hectares", str(area_ha)),
            ("Cleared_Area_Acres", str(props.get("area_acres", round(area_ha * 2.47, 2)))),
            ("Severity_Level", severity),
            ("Urgency_Code", urgency),
            ("Estimated_CO2_Loss_Tonnes", str(carbon)),
            ("UTM_Coordinates", utm),
            ("Latitude", str(center_lat)),
            ("Longitude", str(center_lon)),
            ("Verification_Status", props.get("status", "PENDING_FIELD_VERIFICATION")),
        ]:
            data_tag = ET.SubElement(ext_data, "Data", name=k)
            ET.SubElement(data_tag, "value").text = v

        # Popup Description HTML
        desc = ET.SubElement(placemark, "description")
        desc.text = f"""
        <![CDATA[
        <div style="font-family: Arial, sans-serif; padding: 8px;">
            <h3 style="color: #b71c1c; margin-bottom: 4px;">{alert_id} | Deforestation Alert</h3>
            <table border="1" cellpadding="5" cellspacing="0" style="border-collapse: collapse; width: 100%;">
                <tr bgcolor="#f5f5f5"><td><b>Cleared Area:</b></td><td><b>{area_ha} ha</b> ({props.get('area_acres', 0)} acres)</td></tr>
                <tr><td><b>Severity:</b></td><td>{severity}</td></tr>
                <tr bgcolor="#f5f5f5"><td><b>Urgency:</b></td><td><span style="color: red; font-weight: bold;">{urgency}</span></td></tr>
                <tr><td><b>Biomass Carbon:</b></td><td>{carbon} t CO₂</td></tr>
                <tr bgcolor="#f5f5f5"><td><b>Centroid:</b></td><td>{center_lat:.5f}°N, {center_lon:.5f}°E</td></tr>
                <tr><td><b>UTM Grid:</b></td><td>{utm}</td></tr>
                <tr bgcolor="#f5f5f5"><td><b>Division:</b></td><td>Hasdeo Arand, Surguja (C.G.)</td></tr>
            </table>
            <p style="margin-top: 8px; font-size: 11px; color: #666;">ISRO NRSC Bhuvan Integration Standard</p>
        </div>
        ]]>
        """

        # Polygon coordinates (lon,lat,alt)
        coords_list = geom.get("coordinates", [[]])[0]
        coord_str_parts = []
        for pt in coords_list:
            if len(pt) >= 2:
                coord_str_parts.append(f"{pt[0]},{pt[1]},0")
        coord_text = " ".join(coord_str_parts)

        poly_el = ET.SubElement(placemark, "Polygon")
        ET.SubElement(poly_el, "extrude").text = "1"
        ET.SubElement(poly_el, "altitudeMode").text = "clampToGround"
        outer_bound = ET.SubElement(poly_el, "outerBoundaryIs")
        lin_ring = ET.SubElement(outer_bound, "LinearRing")
        ET.SubElement(lin_ring, "coordinates").text = coord_text

    tree = ET.ElementTree(kml)
    ET.indent(tree, space="  ", level=0)
    tree.write(output_kml_path, encoding="utf-8", xml_declaration=True)

    print(f"[Bhuvan Export] Successfully generated ISRO Bhuvan KML: {output_kml_path} ({len(features)} alerts)")
    return output_kml_path
