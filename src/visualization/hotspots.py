def hotspot_by_code(code: str) -> Dict[str, Any]:
    for item in HOTSPOTS.values():
        if item["code"] == code:
            return item
    return HOTSPOTS["hasdeo_arand_india"]


def india_keys() -> Tuple[str, ...]:
    return tuple(key for key, item in HOTSPOTS.items() if item.get("flag") == "IN")


